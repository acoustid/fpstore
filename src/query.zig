//! The hashes of a fingerprint that fpindex indexes it under and searches it
//! by, as pg_acoustid's `acoustid_extract_query` picks them.
//!
//! Up to 120 distinct hashes, masked to their top 28 bits, starting 80 hashes
//! in, or earlier when the fingerprint is too short to have 120 after that,
//! and skipping silence. The index already holds queries extracted this way,
//! so unlike the similarity score, this has to match pg_acoustid exactly.

const std = @import("std");

pub const max_length = 120;

const start = 80;
const mask: u32 = 0xFFFFFFF0;
const silence: u32 = 627964279;

/// Extracts the query of `hashes` into `out`, in the order the hashes come in,
/// and returns the part of `out` it fills, empty for a fingerprint of nothing
/// but silence.
pub fn extract(hashes: []const u32, out: *[max_length]u32) []u32 {
    const clean_len = hashes.len - std.mem.count(u32, hashes, &.{silence});
    if (clean_len == 0) return out[0..0];

    // Counted without silence, but used as a position among all the hashes,
    // as pg_acoustid does.
    const first = if (clean_len > max_length) @min(clean_len - max_length, start) else 0;

    var len: usize = 0;
    for (hashes[first..]) |hash| {
        if (len == max_length) break;
        if (hash == silence) continue;
        const x = hash & mask;
        if (std.mem.indexOfScalar(u32, out[0..len], x) != null) continue;
        out[len] = x;
        len += 1;
    }
    return out[0..len];
}

const testing = std.testing;

test "masks to the top 28 bits and drops silence and duplicates" {
    var out: [max_length]u32 = undefined;
    const minus_one: u32 = @bitCast(@as(i32, -1));
    try testing.expectEqualSlices(u32, &.{ 0, 0xFFFFFFF0 }, extract(&.{ 1, 2, silence, 3, minus_one }, &out));
}

test "nothing but silence gives an empty query" {
    var out: [max_length]u32 = undefined;
    try testing.expectEqual(0, extract(&.{}, &out).len);
    try testing.expectEqual(0, extract(&.{ silence, silence }, &out).len);
}

/// What pg_acoustid gives for the fingerprints of the compare tests ("fp",
/// by position) and for synthetic ones written out in full ("raw"),
/// generated by tools/query-golden.
const golden = @embedFile("testdata/query/golden.txt");

fn parseHashes(allocator: std.mem.Allocator, text: []const u8) ![]u32 {
    var list: std.ArrayList(u32) = .empty;
    errdefer list.deinit(allocator);
    var it = std.mem.tokenizeAny(u8, text, ", ");
    while (it.next()) |x| try list.append(allocator, try std.fmt.parseInt(u32, x, 10));
    return list.toOwnedSlice(allocator);
}

test "matches pg_acoustid" {
    const allocator = testing.allocator;
    const encoding = @import("encoding.zig");
    const fingerprints = @embedFile("testdata/compare/fingerprints.bin");

    var offsets: std.ArrayList(usize) = .empty;
    defer offsets.deinit(allocator);
    var pos: usize = 0;
    while (pos < fingerprints.len) {
        try offsets.append(allocator, pos);
        pos += 4 + std.mem.readInt(u32, fingerprints[pos..][0..4], .little);
    }

    var num_fp: usize = 0;
    var num_raw: usize = 0;
    var lines = std.mem.tokenizeScalar(u8, golden, '\n');
    while (lines.next()) |line| {
        if (line[0] == '#') continue;
        errdefer std.debug.print("line: {s}\n", .{line[0..@min(line.len, 80)]});
        const bar = std.mem.indexOfScalar(u8, line, '|').?;
        const expected = try parseHashes(allocator, line[bar + 1 ..]);
        defer allocator.free(expected);

        const input = line[0..bar];
        const hashes = if (std.mem.startsWith(u8, input, "fp ")) blk: {
            num_fp += 1;
            const at = offsets.items[try std.fmt.parseInt(usize, std.mem.trim(u8, input[3..], " "), 10)];
            const data = fingerprints[at + 4 ..][0..std.mem.readInt(u32, fingerprints[at..][0..4], .little)];
            const hashes = try allocator.alloc(u32, (try encoding.decodeHeader(data)).num_hashes);
            errdefer allocator.free(hashes);
            const scratch = try allocator.alloc(u8, encoding.decodeScratchSize(data.len));
            defer allocator.free(scratch);
            _ = try encoding.decode(data, hashes, scratch);
            break :blk hashes;
        } else blk: {
            num_raw += 1;
            break :blk try parseHashes(allocator, input[3..]);
        };
        defer allocator.free(hashes);

        var out: [max_length]u32 = undefined;
        try testing.expectEqualSlices(u32, expected, extract(hashes, &out));
    }
    try testing.expect(num_fp > 100);
    try testing.expect(num_raw > 10);
}
