//! Generates src/testdata/query/golden.txt, which src/query.zig is tested
//! against: what pg_acoustid's acoustid_extract_query gives for the
//! fingerprints in src/testdata/compare/fingerprints.bin, and for synthetic
//! ones around the edges of the start position, silence and duplicates.
//!
//!     zig build query-golden -- postgresql://postgres:password@127.0.0.1:5432/postgres
//!
//! The database needs the acoustid extension.

const std = @import("std");
const zio = @import("zio");
const pg = @import("pg");
const encoding = @import("encoding");

const silence: u32 = 627964279;

fn run(allocator: std.mem.Allocator, rt: *zio.Runtime, url: []const u8, fingerprints_path: []const u8, out_path: []const u8) !void {
    const io = rt.io();
    const pool = try pg.Pool.initUri(io, allocator, try std.Uri.parse(url), .{ .size = 1 });
    defer pool.deinit();
    _ = try pool.exec("CREATE EXTENSION IF NOT EXISTS acoustid", .{});

    var arena_state = std.heap.ArenaAllocator.init(allocator);
    defer arena_state.deinit();
    const arena = arena_state.allocator();

    const out = try std.Io.Dir.cwd().createFile(io, out_path, .{});
    defer out.close(io);
    var out_buf: [64 * 1024]u8 = undefined;
    var w = out.writer(io, &out_buf);

    try w.interface.writeAll("# input | acoustid_extract_query  (generated by tools/query-golden)\n");

    // The fingerprints of the compare tests, by their position in the file.
    const data = try std.Io.Dir.cwd().readFileAlloc(io, fingerprints_path, arena, .unlimited);
    var pos: usize = 0;
    var index: usize = 0;
    while (pos < data.len) : (index += 1) {
        const len = std.mem.readInt(u32, data[pos..][0..4], .little);
        const fp = data[pos + 4 ..][0..len];
        pos += 4 + len;
        const header = try encoding.decodeHeader(fp);
        const hashes = try arena.alloc(u32, header.num_hashes);
        _ = try encoding.decode(fp, hashes, try arena.alloc(u8, encoding.decodeScratchSize(fp.len)));
        try w.interface.print("fp {d} |", .{index});
        try writeQuery(&w.interface, pool, hashes);
    }

    // Synthetic ones, written out in full.
    var prng = std.Random.DefaultPrng.init(3);
    const random = prng.random();
    var cases: std.ArrayList([]const u32) = .empty;
    try cases.append(arena, &.{});
    try cases.append(arena, &.{0x12345678});
    try cases.append(arena, &.{ silence, silence, silence });
    // Around where the start moves off 0 and reaches 80.
    for ([_]usize{ 119, 120, 121, 150, 199, 200, 201, 300 }) |n| {
        try cases.append(arena, try randomHashes(arena, random, n));
    }
    // Silence before, among and after the hashes the start is counted from.
    for ([_][3]usize{ .{ 100, 150, 0 }, .{ 50, 250, 50 }, .{ 0, 130, 100 }, .{ 200, 119, 0 } }) |spec| {
        const h = try arena.alloc(u32, spec[0] + spec[1] + spec[2]);
        @memset(h, silence);
        for (h[spec[0]..][0..spec[1]]) |*x| x.* = random.int(u32);
        try cases.append(arena, h);
    }
    {
        // Silence scattered through.
        const h = try randomHashes(arena, random, 400);
        for (h) |*x| {
            if (random.uintLessThan(u32, 3) == 0) x.* = silence;
        }
        try cases.append(arena, h);
    }
    {
        // Few distinct values, so the query runs out before 120.
        const h = try arena.alloc(u32, 300);
        for (h) |*x| x.* = random.uintLessThan(u32, 10) << 20;
        try cases.append(arena, h);
    }
    {
        // Values that differ only in the bits the mask drops.
        const h = try arena.alloc(u32, 300);
        for (h, 0..) |*x, i| x.* = (@as(u32, @intCast(i / 16)) << 4) | random.uintLessThan(u32, 16);
        try cases.append(arena, h);
    }
    {
        // Silence once masked, but not silence itself.
        const h = try randomHashes(arena, random, 250);
        for (h[0..50]) |*x| x.* = silence ^ 1;
        try cases.append(arena, h);
    }
    for (cases.items) |hashes| {
        try w.interface.writeAll("raw");
        for (hashes, 0..) |x, i| try w.interface.print("{s}{d}", .{ if (i == 0) " " else ",", x });
        try w.interface.writeAll(" |");
        try writeQuery(&w.interface, pool, hashes);
    }
    try w.interface.flush();
}

fn randomHashes(arena: std.mem.Allocator, random: std.Random, n: usize) ![]u32 {
    const h = try arena.alloc(u32, n);
    for (h) |*x| x.* = random.int(u32);
    return h;
}

fn writeQuery(w: *std.Io.Writer, pool: *pg.Pool, hashes: []const u32) !void {
    // Bound as int4[], which takes i32s, with the same bits.
    const signed: []const i32 = @ptrCast(hashes);
    var result = try pool.query("SELECT acoustid_extract_query($1::int4[])", .{signed});
    defer result.deinit();
    const row = try result.next() orelse return error.NoRow;
    var it = try row.get(pg.Iterator(i32), 0);
    var i: usize = 0;
    while (it.next()) |x| : (i += 1) {
        try w.print("{s}{d}", .{ if (i == 0) " " else ",", @as(u32, @bitCast(x)) });
    }
    try result.drain();
    try w.writeAll("\n");
}

pub fn main(init: std.process.Init.Minimal) !void {
    var gpa: std.heap.DebugAllocator(.{}) = .{};
    defer _ = gpa.deinit();
    const allocator = gpa.allocator();

    var it = std.process.Args.Iterator.init(init.args);
    _ = it.skip();
    const url = it.next() orelse return error.MissingArgument;
    const fingerprints_path = it.next() orelse "src/testdata/compare/fingerprints.bin";
    const out_path = it.next() orelse "src/testdata/query/golden.txt";

    var rt = try zio.Runtime.init(allocator, .{});
    defer rt.deinit();
    var task = try zio.spawn(run, .{ allocator, rt, url, fingerprints_path, out_path });
    try task.join();
}
